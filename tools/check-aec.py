#!/usr/bin/env python3
"""Is Chrome's echoCancellation actually removing Helix's own voice from the mic?

The OS-level leak is real (measured separately: RMS 2126-4836, peaks to 100%).
If AEC is doing its job the leak should fall sharply. This records the mic with
AEC ON and AEC OFF, under identical conditions, and reports the difference.

Uses real getUserMedia in a real browser; no Speech API, no stored audio. The
signal played is synthetic TTS generated by the local bridge.
"""
import asyncio, json, math, os, subprocess, sys, time, urllib.request

CHROME, PORT, PROF = "/usr/bin/google-chrome", 9380, "/tmp/helix-aec2"
URL = "http://127.0.0.1:8787/voice-core/"
PROMPT = "/tmp/echotest/p.wav"
REC = "/tmp/echotest/aec-{}.wav"

# One evaluate, no injection games: grab a stream, report the settings the
# browser actually granted, then buffer N seconds of mic level.
MEASURE = r"""
(async function(){
  var aec = arguments[0];
  var out = {requested: aec, error: null, settings: null, rms: [], peak: 0};
  try {
    var s = await navigator.mediaDevices.getUserMedia({audio:{
      channelCount:1, echoCancellation:aec, noiseSuppression:false, autoGainControl:false}});
    var tr = s.getAudioTracks()[0];
    out.settings = tr.getSettings();
    var AC = window.AudioContext || window.webkitAudioContext;
    var ctx = new AC();
    var an = ctx.createAnalyser(); an.fftSize = 2048;
    ctx.createMediaStreamSource(s).connect(an);
    var buf = new Uint8Array(an.fftSize);
    for (var k=0;k<40;k++){
      await new Promise(function(r){ setTimeout(r,100); });
      an.getByteTimeDomainData(buf);
      var sum=0, pk=0;
      for (var i=0;i<buf.length;i++){ var d=(buf[i]-128)/128; sum+=d*d; var a=Math.abs(d); if(a>pk)pk=a; }
      out.rms.push(Math.sqrt(sum/buf.length));
      if (pk>out.peak) out.peak=pk;
    }
    s.getTracks().forEach(function(x){x.stop()});
  } catch(e){ out.error = e.name + ': ' + e.message; }
  return JSON.stringify(out);
})()
"""


def targets():
    with urllib.request.urlopen(f"http://127.0.0.1:{PORT}/json/list", timeout=5) as r:
        return json.load(r)


async def run_case(ws, js, aec, label):
    # record with arecord so the level is measured outside the browser too
    rec = subprocess.Popen(["arecord", "-f", "S16_LE", "-r", "16000", "-c", "1",
                            "-d", "8", "-D", "default", REC.format(label)],
                           stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    await asyncio.sleep(1)
    task = asyncio.create_task(js(MEASURE.replace("arguments[0]", json.dumps(aec)),
                                  awaitp=True))
    await asyncio.sleep(1.2)
    subprocess.run(["aplay", "-q", "-D", "default", PROMPT],
                   stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    v = await task
    rec.terminate(); await asyncio.sleep(0.6)

    d = json.loads(v) if isinstance(v, str) else {"error": str(v)[:160]}
    rs = d.get("rms") or []
    inb = math_rms(REC.format(label))
    print(f"\n  --- {label} (echoCancellation={aec}) ---")
    print(f"    browser error : {d.get('error')}")
    st = d.get("settings") or {}
    print(f"    granted settings: echoCancellation={st.get('echoCancellation')} "
          f"noiseSuppression={st.get('noiseSuppression')} autoGainControl={st.get('autoGainControl')}")
    if rs:
        peak_r = max(rs)
        print(f"    in-browser mic RMS: peak {peak_r:.4f}  mean {sum(rs)/len(rs):.4f}")
    print(f"    arecord RMS      : {inb:.4f}")
    return rs, inb


def math_rms(path):
    import wave, struct, math
    try:
        w = wave.open(path); n = w.getnframes()
        s = struct.unpack(f"<{n}h", w.readframes(n))
        return math.sqrt(sum(x * x for x in s) / n) / 32768.0
    except Exception:
        return float("nan")


async def main():
    proc = subprocess.Popen([
        CHROME, "--headless=new", f"--remote-debugging-port={PORT}",
        f"--user-data-dir={PROF}", "--use-fake-ui-for-media-stream",
        "--autoplay-policy=no-user-gesture-required", "--no-sandbox",
        "--disable-gpu", URL], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    tgt = None
    for _ in range(50):
        time.sleep(0.5)
        try:
            tgt = next((t for t in targets() if t.get("type") == "page"), None)
        except Exception:
            pass
        if tgt:
            break
    if not tgt:
        print("  FAIL: no page"); proc.terminate(); return 2
    try:
        from websockets.asyncio.client import connect
        async with connect(tgt["webSocketDebuggerUrl"], max_size=None) as ws:
            n = [0]
            async def js(e, awaitp=False):
                n[0] += 1
                await ws.send(json.dumps({"id": n[0], "method": "Runtime.evaluate",
                                          "params": {"expression": e,
                                                     "returnByValue": True,
                                                     "awaitPromise": awaitp}}))
                while True:
                    m = json.loads(await ws.recv())
                    if m.get("id") == n[0]:
                        r = m.get("result", {})
                        if "exceptionDetails" in r:
                            return "EXC:" + json.dumps(r["exceptionDetails"])[:200]
                        return r.get("result", {}).get("result", {}).get("value")
            await asyncio.sleep(3)
            on_rms, on_disk = await run_case(ws, js, True, "aec-on")
            off_rms, off_disk = await run_case(ws, js, False, "aec-off")
            print("\n  === verdict ===")
            print(f"    mic level with AEC on : {on_disk:.4f}")
            print(f"    mic level with AEC off: {off_disk:.4f}")
            if off_disk > 0 and on_disk == off_disk:
                print("    AEC had NO effect -> the leak is irreducible without headphones")
            elif off_disk > 0:
                print(f"    AEC reduced the leak by "
                      f"{(1 - on_disk / off_disk) * 100:.0f}%")
            return 0
    finally:
        proc.terminate()
        try:
            proc.wait(timeout=8)
        except Exception:
            proc.kill()


sys.exit(asyncio.run(main()))